import { readFile } from 'node:fs/promises';
import process from 'node:process';
import pg from 'pg';

const sourcePath = process.argv[2] ?? 'work/d1-production-export.sql';
const resetTarget = process.argv.includes('--reset');
const addForeignKeysOnly = process.argv.includes('--add-foreign-keys');
const connectionString = process.env.DATABASE_URL;
if (!connectionString) throw new Error('DATABASE_URL is required. Do not add it to source control.');

function postgresSql(sql) {
  return sql
    .replace(/^PRAGMA[^;]*;\s*/gm, '')
    .replace(/INTEGER PRIMARY KEY AUTOINCREMENT/gi, 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bBLOB\b/gi, 'BYTEA')
    .replace(/TEXT(\s+NOT NULL)?\s+UNIQUE\s+COLLATE NOCASE/gi, 'CITEXT$1 UNIQUE')
    .replace(/strftime\('%Y-%m-%dT%H:%M:%fZ','now'\)/g, "to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"')")
    .replace(/datetime\('now', '\+7 days'\)/g, "((CURRENT_TIMESTAMP AT TIME ZONE 'UTC') + INTERVAL '7 days')::text")
    .replace(/datetime\('now'\)/g, "(CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::text")
    .replace(/date\('now'\)/g, 'CURRENT_DATE::text');
}

function splitStatements(sql) {
  const statements = [];
  let start = 0;
  let quote = null;

  for (let index = 0; index < sql.length; index += 1) {
    const character = sql[index];
    if (quote) {
      if (character === quote) {
        if (sql[index + 1] === quote) index += 1;
        else quote = null;
      }
      continue;
    }
    if (character === "'" || character === '"') quote = character;
    else if (character === ';') {
      const statement = sql.slice(start, index).trim();
      if (statement) statements.push(statement);
      start = index + 1;
    }
  }
  const finalStatement = sql.slice(start).trim();
  if (finalStatement) statements.push(finalStatement);
  return statements;
}

function extractForeignKeys(tableStatement) {
  const tableMatch = tableStatement.match(/^CREATE TABLE(?: IF NOT EXISTS)?\s+"?([\w]+)"?/i);
  if (!tableMatch) return [];
  const tableName = tableMatch[1];
  const foreignKeys = [];
  const referencePattern = /(?:^|,|\n)\s*"?([\w]+)"?\s+[^,\n]*?\s+REFERENCES\s+"?([\w]+)"?\s*\(\s*"?([\w]+)"?\s*\)/gi;
  for (const match of tableStatement.matchAll(referencePattern)) {
    foreignKeys.push(`ALTER TABLE "${tableName}" ADD FOREIGN KEY ("${match[1]}") REFERENCES "${match[2]}" ("${match[3]}")`);
  }
  return foreignKeys;
}

function removeForeignKeyReferences(tableStatement) {
  return tableStatement.replace(/\s+REFERENCES\s+"?[\w]+"?\s*\(\s*"?[\w]+"?\s*\)/gi, '');
}

const dump = await readFile(sourcePath, 'utf8');
const pool = new pg.Pool({ connectionString, ssl: { rejectUnauthorized: true }, max: 1 });
try {
  if (resetTarget) {
    await pool.query('DROP SCHEMA public CASCADE; CREATE SCHEMA public;');
  }
  await pool.query('CREATE EXTENSION IF NOT EXISTS citext;');
  const statements = splitStatements(postgresSql(dump));
  const tableStatements = statements.filter((statement) => /^CREATE TABLE/i.test(statement));
  const dataStatements = statements.filter((statement) => /^INSERT INTO/i.test(statement));
  const indexStatements = statements.filter((statement) => /^CREATE (UNIQUE )?INDEX/i.test(statement));
  const foreignKeys = tableStatements.flatMap(extractForeignKeys);

  if (!addForeignKeysOnly) {
    for (const statement of tableStatements) await pool.query(removeForeignKeyReferences(statement));
    for (const statement of dataStatements) await pool.query(statement);
    for (const statement of indexStatements) await pool.query(statement);
  }
  for (const statement of foreignKeys) await pool.query(statement);
  const { rows } = await pool.query("SELECT COUNT(*)::int AS count FROM information_schema.tables WHERE table_schema = 'public'");
  console.log(`Imported D1 snapshot into PostgreSQL (${rows[0].count} public tables).`);
} finally {
  await pool.end();
}
